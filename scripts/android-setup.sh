#!/usr/bin/env bash
# Patches the generated Android project (android/ is not committed): permissions + speech-service visibility.
set -euo pipefail
f=android/app/src/main/AndroidManifest.xml
add() { grep -q "android.permission.$1\"" "$f" || sed -i "s#</manifest>#    <uses-permission android:name=\"android.permission.$1\" />\n</manifest>#" "$f"; }
for p in INTERNET RECORD_AUDIO MODIFY_AUDIO_SETTINGS VIBRATE POST_NOTIFICATIONS WAKE_LOCK; do add "$p"; done
# microphone is optional hardware: do not hide the app from devices without it
grep -q "hardware.microphone" "$f" || sed -i 's#</manifest>#    <uses-feature android:name="android.hardware.microphone" android:required="false" />\n</manifest>#' "$f"
# Android 11+ package visibility: lets the app find the system speech recogniser
grep -q "android.speech.RecognitionService" "$f" || sed -i 's#</manifest>#    <queries>\n        <intent><action android:name="android.speech.RecognitionService" /></intent>\n    </queries>\n</manifest>#' "$f"
echo "--- manifest permissions"; grep -E "uses-permission|uses-feature|RecognitionService" "$f"

# --- app icon + splash (generated by scripts/make-icons.py from assets/icon-source.jpg, committed in assets/android-res) ---
res=android/app/src/main/res
cp -r assets/android-res/. "$res/"
find "$res" -name 'splash.png' -delete   # default Capacitor splash bitmaps: replaced by drawable/splash.xml (navy + centred art)
find "$res" -name 'ic_launcher_foreground.xml' -delete 2>/dev/null || true  # default vector foreground: replaced by our PNG layers
echo "--- icon resources"; ls "$res"/mipmap-xxxhdpi "$res"/drawable 2>/dev/null

# --- system bars / keyboard: navy window behind the (margin-adjusted) web content, resize when the keyboard opens ---
st=android/app/src/main/res/values/styles.xml
if ! grep -q "windowBackground" "$st"; then
  sed -i 's#<item name="android:background">@null</item>#<item name="android:background">@null</item>\n        <item name="android:windowBackground">@color/ic_launcher_background</item>\n        <item name="android:statusBarColor">@color/ic_launcher_background</item>\n        <item name="android:navigationBarColor">@color/ic_launcher_background</item>\n        <item name="android:windowLightStatusBar">false</item>#' "$st"
fi
grep -q "windowSoftInputMode" "$f" || sed -i 's#<activity#<activity android:windowSoftInputMode="adjustResize"#' "$f"
echo "--- theme + activity"; grep -E "windowBackground|statusBarColor|windowSoftInputMode" "$st" "$f"

# Landscape reading mode: hide system bars (immersive) when the phone is turned sideways.
MA=$(find android/app/src/main/java -name MainActivity.java | head -1)
cp scripts/native/MainActivity.java "$MA"
